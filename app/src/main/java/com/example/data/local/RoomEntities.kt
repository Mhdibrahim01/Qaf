    @ColumnInfo(name = "mastered_count") val masteredCount: Int = 0,
    @ColumnInfo(name = "favorite_count") val favoriteCount: Int = 0,
    @ColumnInfo(name = "display_order") val displayOrder: Int = 0
) {
    val name: String get() = title
    val nameAr: String get() = arabicSubtitle
}

