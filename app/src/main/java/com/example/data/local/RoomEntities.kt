/**
 * Raw JSON entry representation for the 7 data_import JSON files and generated decks.
 * Fields: id, type (word | academic | phrase | expression | idiom), deck, text,
 * pos, level (A1-C1, may be empty), ipa, definition_en, note_en,
 * examples_en (sentences separated by " | "), examples_ar (separated by " | "),
 * definition_url, audio_url, arabic, arabic_source ("file" | "ai" | "user" | "").
 */
@Serializable
data class RawJsonEntry(
    val id: JsonPrimitive,
    val type: String = "word",
    val deck: String = "",
    val text: String = "",
    val pos: String = "",
    val level: String = "",
    val ipa: String = "",
    @SerialName("definition_en") val definitionEn: String = "",
    @SerialName("note_en") val noteEn: String = "",
    @SerialName("examples_en") val examplesEn: String = "",
    @SerialName("examples_ar") val examplesAr: String = "",
    @SerialName("definition_url") val definitionUrl: String = "",
    @SerialName("audio_url") val audioUrl: String = "",
    val arabic: String = "",
    @SerialName("arabic_source") val arabicSource: String = ""
)

