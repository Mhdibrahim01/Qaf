/**
 * 1. entries table
 * Stores all imported vocabulary rows (9,862 core entries + optional generated decks).
 * Same word (`text`) with different `pos` in the same `deck` is grouped into a single card
 * with POS tabs in the UI layer.
 *
 * `arabicSource` tracks where `arabic` came from:
 * - ""     : Arabic is empty
 * - "file" : Imported from JSON file
 * - "ai"   : Generated by Gemini AI (either in-app or from generate_decks.py with arabic_source="ai")
 * - "user" : Edited by the user (NEVER overwritten by imports or AI)
 *
 * `dataVersion` tracks the schema/content version of the imported entry so content upserts by id
 * can update content fields without touching `word_progress` or `sentences`.
 */
@Immutable
@Entity(
    tableName = "entries",
    indices = [
        Index(value = ["deck"]),
        Index(value = ["text"]),
        Index(value = ["deck", "text"]),
        Index(value = ["level"]),
        Index(value = ["type"]),
        Index(value = ["arabic_source"])
    ]
)
data class EntryEntity(
    @PrimaryKey val id: String,
    val type: String,
    val deck: String,
    val text: String,
    val pos: String,
    val level: String,
    @ColumnInfo(name = "definition_en") val definitionEn: String,
    @ColumnInfo(name = "note_en") val noteEn: String,
    @ColumnInfo(name = "examples_en") val examplesEn: String,
    @ColumnInfo(name = "examples_ar") val examplesAr: String = "",
    @ColumnInfo(name = "definition_url") val definitionUrl: String,
    @ColumnInfo(name = "audio_url") val audioUrl: String,
    val arabic: String,
    @ColumnInfo(name = "arabic_source") val arabicSource: String = "",
    val ipa: String = "",
    val syllables: String = "",
    @ColumnInfo(name = "extra_examples_json") val extraExamplesJson: String = "",
    @ColumnInfo(name = "data_version") val dataVersion: Int = 1
)

/**
